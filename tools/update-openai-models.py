#!/usr/bin/env python3
"""Regenerate the bundled OpenAI catalog from Codex model metadata."""
import json
from pathlib import Path
import re
import sys
import urllib.request

URL = "https://raw.githubusercontent.com/openai/codex/main/codex-rs/models-manager/models.json"
EFFORTS = {"none", "minimal", "low", "medium", "high", "xhigh", "max"}
OUTPUT = Path(__file__).resolve().parents[1] / "src/core/providers/openai_models.zig"


def generate(data):
    models = []
    seen = set()
    for model in sorted(data["models"], key=lambda m: m["priority"]):
        if model["visibility"] != "list" or not model["supported_in_api"]:
            continue
        name = model["slug"]
        if not re.fullmatch(r"[a-zA-Z0-9._/-]{1,200}", name) or name in seen:
            raise ValueError("invalid or duplicate model ID")
        seen.add(name)
        # Client-side orchestration modes such as ultra are not API effort levels.
        efforts = [x["effort"] for x in model["supported_reasoning_levels"] if x["effort"] in EFFORTS]
        default = model["default_reasoning_level"]
        if not efforts or len(efforts) != len(set(efforts)) or default not in efforts:
            raise ValueError("invalid reasoning metadata")
        models.append((name, default, efforts))
    if not models:
        raise ValueError("empty model catalog")
    lines = [
        "//! Generated by tools/update-openai-models.py; do not edit by hand.",
        f"//! Source: {URL}",
        'const std = @import("std");',
        "pub const Entry = struct { id: []const u8, default_effort: []const u8, efforts: []const []const u8 };",
        "pub const entries = [_]Entry{",
    ]
    for name, default, efforts in models:
        wire = ", ".join(json.dumps(x) for x in efforts)
        lines.append(f"    .{{ .id = {json.dumps(name)}, .default_effort = {json.dumps(default)}, .efforts = &.{{ {wire} }} }},")
    lines += ["};", "", "pub const ids = blk: {", "    var result: [entries.len][]const u8 = undefined;",
              "    for (entries, 0..) |entry, i| result[i] = entry.id;", "    break :blk result;", "};", "",
              "pub fn find(id: []const u8) ?Entry {", "    for (entries) |entry| {",
              "        if (std.mem.eql(u8, entry.id, id)) return entry;", "    }", "    return null;", "}", ""]
    return "\n".join(lines)


def self_test():
    model = {"slug": "future-model", "priority": 0, "visibility": "list", "supported_in_api": True,
             "default_reasoning_level": "low", "supported_reasoning_levels": [{"effort": "low"}, {"effort": "max"}, {"effort": "ultra"}]}
    text = generate({"models": [model]})
    assert '"future-model"' in text and '.efforts = &.{ "low", "max" }' in text
    for data in ({"models": []}, {"models": [model, model]}, {"models": [{**model, "default_reasoning_level": "none"}]}):
        try:
            generate(data)
        except ValueError:
            pass
        else:
            raise AssertionError("invalid catalog accepted")


if __name__ == "__main__":
    if sys.argv[1:] == ["--self-test"]:
        self_test()
    else:
        if len(sys.argv) > 2:
            raise SystemExit("usage: update-openai-models.py [catalog.json | --self-test]")
        if len(sys.argv) == 2:
            data = json.loads(Path(sys.argv[1]).read_text())
        else:
            with urllib.request.urlopen(URL, timeout=30) as response:
                raw = response.read(8 * 1024 * 1024 + 1)
            if len(raw) > 8 * 1024 * 1024:
                raise ValueError("catalog exceeds 8 MiB")
            data = json.loads(raw)
        text = generate(data)
        temp = OUTPUT.with_suffix(".zig.tmp")
        temp.write_text(text)
        temp.replace(OUTPUT)
